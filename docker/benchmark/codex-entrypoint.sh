#!/bin/sh
# Entrypoint of the benchmark image: make sure Codex CLI has a config.toml,
# then run the requested command (pytest by default, or whatever `docker
# compose run benchmark ...` passes).
#
# If the user bind-mounts their own config.toml at $CODEX_HOME/config.toml it
# is left untouched; otherwise one is generated from environment variables:
#
#   CODEX_MODEL       model id                     (default: gpt-5-codex)
#   CODEX_PROVIDER    provider name                (default: openai)
#   CODEX_BASE_URL    OpenAI-compatible endpoint   (default: https://api.openai.com/v1)
#   CODEX_ENV_KEY     env var holding the API key  (default: OPENAI_API_KEY)
#   CODEX_WIRE_API    "responses" or "chat"        (default: responses for openai, chat otherwise)
#   MCP_URL           Blender MCP endpoint         (default: http://blender:8000/mcp)
#
# OpenRouter example (.env):
#   CODEX_PROVIDER=openrouter
#   CODEX_BASE_URL=https://openrouter.ai/api/v1
#   CODEX_ENV_KEY=OPENROUTER_API_KEY
#   CODEX_MODEL=openai/gpt-5-codex
#   OPENROUTER_API_KEY=sk-or-...
set -eu

CODEX_HOME="${CODEX_HOME:-$HOME/.codex}"
CONFIG="$CODEX_HOME/config.toml"

if [ ! -f "$CONFIG" ]; then
    mkdir -p "$CODEX_HOME"
    MODEL="${CODEX_MODEL:-gpt-5-codex}"
    PROVIDER="${CODEX_PROVIDER:-openai}"
    MCP_URL_VALUE="${MCP_URL:-http://blender:8000/mcp}"
    {
        echo "# Generated by codex-entrypoint.sh from environment variables."
        echo "# Mount your own file at $CONFIG to take full control."
        echo "model = \"$MODEL\""
        echo "model_provider = \"$PROVIDER\""
        # The built-in "openai" provider already reads OPENAI_API_KEY; only
        # (re)define a provider section for third-party endpoints or an
        # explicitly overridden base URL.
        if [ "$PROVIDER" != "openai" ] || [ -n "${CODEX_BASE_URL:-}" ]; then
            BASE_URL="${CODEX_BASE_URL:-https://api.openai.com/v1}"
            ENV_KEY="${CODEX_ENV_KEY:-OPENAI_API_KEY}"
            WIRE_API="${CODEX_WIRE_API:-chat}"
            echo ""
            echo "[model_providers.$PROVIDER]"
            echo "name = \"$PROVIDER\""
            echo "base_url = \"$BASE_URL\""
            echo "env_key = \"$ENV_KEY\""
            echo "wire_api = \"$WIRE_API\""
        fi
        echo ""
        echo "[mcp_servers.blender]"
        echo "url = \"$MCP_URL_VALUE\""
    } > "$CONFIG"
fi

exec "$@"
